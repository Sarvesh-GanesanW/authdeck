// Builds src/ui/pixelIcons.ts from the pixelarticons package (a dev dependency).
// Run: node scripts/gen-pixel-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules', 'pixelarticons');
const svgDir = join(pkg, 'svg');
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;
const license = readFileSync(join(pkg, 'LICENSE'), 'utf8').trim();

const all = new Set(readdirSync(svgDir).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)));
// Keep the regular style; take a "-sharp" icon only when it has no regular twin.
const names = [...all]
  .filter((n) => !n.endsWith('-sharp') || !all.has(n.slice(0, -'-sharp'.length)))
  .sort();

const icons = {};
for (const name of names) {
  const svg = readFileSync(join(svgDir, `${name}.svg`), 'utf8');
  // Faint decorative layers (opacity < 1) are dropped: keys draw icons in one solid colour.
  const paths = [...svg.matchAll(/<path\s+d="([^"]+)"([^>]*)\/?>/g)]
    .filter((m) => !/opacity=/.test(m[2]))
    .map((m) => m[1]);
  if (paths.length === 0) throw new Error(`${name}: no paths`);
  icons[name] = paths.length === 1 ? paths[0] : paths;
}

const out = `/* eslint-disable */
// Generated by scripts/gen-pixel-icons.mjs from pixelarticons ${version}. Do not edit by hand.
//
// Icons: pixelarticons by Gerrit Halfmann, https://github.com/halfmage/pixelarticons
${license.split('\n').map((l) => `// ${l}`.trimEnd()).join('\n')}

/** Every pixel icon name, sorted. Icons are drawn on a 24-unit grid in 2-unit pixels. */
export const GLYPH_NAMES = ${JSON.stringify(names)} as const;

export type GlyphName = (typeof GLYPH_NAMES)[number];

/** SVG path data for each icon (24 x 24 view box, filled). */
export const PIXEL_ICONS: Record<GlyphName, string | readonly string[]> = ${JSON.stringify(icons)};
`;
writeFileSync(join(root, 'src', 'ui', 'pixelIcons.ts'), out);
console.log(`wrote ${names.length} icons`);
